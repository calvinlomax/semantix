"""Build deterministic guess and level vocabularies; never load word vectors.

wordfreq orders familiar English spellings. WordNet supplies lexical evidence
and inflections, excluding entries whose only evidence is a proper name. The
existing manually curated list remains the stricter source of puzzle words.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from importlib.metadata import version
from pathlib import Path
from typing import Callable, Iterable

from backend.app.engine.morphology import TOKEN, lemma_forms

ROOT = Path(__file__).resolve().parents[2]


def read_words(path: Path) -> list[str]:
    return list(dict.fromkeys(line.strip() for line in path.read_text(encoding="utf-8").splitlines()
                             if line.strip() and not line.lstrip().startswith("#")))


def wordnet_lexicon() -> tuple[set[str], set[str]]:
    # Initialize the local corpus once through the same configured data path.
    lemma_forms("word")
    from nltk.corpus import wordnet

    common, proper = set(), set()
    for synset in wordnet.all_synsets():
        named_instance = bool(synset.instance_hypernyms())
        for lemma in synset.lemmas():
            name = lemma.name()
            if not TOKEN.fullmatch(name.lower()):
                continue
            if not named_instance and name.islower():
                common.add(name)
            else:
                proper.add(name.lower())
    # A common sense is legitimate even if another sense is a person's name.
    return common, proper - common


def build_vocabularies(
    curated: Iterable[str], frequency_words: Iterable[str], lexical_words: set[str],
    proper_only: set[str], blocked: Iterable[str], *, size: int = 100_000,
    frequency: Callable[[str], float], forms: Callable[[str], frozenset[str]] = lemma_forms,
) -> tuple[list[str], list[str], dict]:
    if not 1 <= size <= 150_000:
        raise ValueError("Choose at most 150,000 guesses; 50,000–100,000 is recommended.")
    blocked_keys = {key for word in blocked for key in ({word} | set(forms(word)))}

    def allowed(word: str) -> bool:
        if not TOKEN.fullmatch(word) or word in proper_only:
            return False
        return not ({word} | set(forms(word))) & blocked_keys

    seed = list(dict.fromkeys(curated))
    # Preserve the manually reviewed order so adding guesses cannot change the
    # target matrix fingerprint, level identities, or daily puzzle selection.
    targets = [word for word in seed if allowed(word)]
    if not targets or len(targets) > size:
        raise ValueError("The guess budget must include every curated level word.")
    candidates = set(targets)
    for word in set(frequency_words) | lexical_words:
        if not allowed(word):
            continue
        if word in lexical_words or forms(word) & lexical_words:
            candidates.add(word)
    ranked = sorted(candidates - set(targets), key=lambda word: (-frequency(word), word))
    guesses = sorted(set(targets) | set(ranked[:size - len(targets)]))
    return guesses, targets, {
        "requested_guess_limit": size, "eligible_guess_count": len(candidates),
        "allowed_guess_count": len(guesses), "level_word_count": len(targets),
        "excluded_curated_words": [word for word in seed if word not in set(targets)],
    }


def write_list(path: Path, words: list[str], description: str, credits: str = "") -> str:
    content = f"# {description}\n# Generated by backend.scripts.build_large_vocab; see README.md.\n" + credits + "\n".join(words) + "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return hashlib.sha256(content.encode()).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--size", type=int, default=100_000, help="Guess source limit (recommended 50k–100k; maximum 150k)")
    parser.add_argument("--curated", type=Path, default=ROOT / "data/vocabulary/words.txt")
    parser.add_argument("--blocked", type=Path, default=ROOT / "data/vocabulary/blocked.txt")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "data/vocabulary")
    args = parser.parse_args()
    try:
        from wordfreq import iter_wordlist, zipf_frequency
        from nltk.corpus import wordnet

        print("Building English vocabulary from wordfreq, WordNet, and curated level words…", flush=True)
        common, proper = wordnet_lexicon()
        guesses, targets, detail = build_vocabularies(
            read_words(args.curated), iter_wordlist("en", wordlist="large"), common, proper,
            read_words(args.blocked), size=args.size,
            frequency=lambda word: zipf_frequency(word, "en", wordlist="large"),
        )
        if detail["excluded_curated_words"]:
            raise ValueError(f"Curated words need review before changing the level catalog: {detail['excluded_curated_words']}")
        hashes = {
            "allowed_guesses.txt": write_list(
                args.output_dir / "allowed_guesses.txt", guesses,
                "Broad guess candidates for Google News extraction; not a runtime allowlist.",
                "# Derived from wordfreq 3.1.1 by Robyn Speer: https://github.com/rspeer/wordfreq\n"
                "# Derived guess-list data: CC BY-SA 4.0, https://creativecommons.org/licenses/by-sa/4.0/\n"
                "# WordNet 3.0, Princeton University: https://wordnet.princeton.edu/license-and-commercial-use\n"
                "# SUBTLEX: Marc Brysbaert and collaborators; freely available frequency data.\n"
                "# Further upstream credits and transformations: data/vocabulary/README.md.\n",
            ),
            "level_words.txt": write_list(args.output_dir / "level_words.txt", targets, "Manually curated, familiar puzzle words; retain this ordering."),
        }
        manifest = {
            "schema_version": 1, "wordfreq_version": version("wordfreq"), "wordnet_version": wordnet.get_version(),
            "sources": {"wordfreq": "https://github.com/rspeer/wordfreq", "wordnet": "https://wordnet.princeton.edu/", "curated": args.curated.name},
            "filters": "lowercase ASCII letters, 2–24 characters, WordNet common lexical evidence or trusted curated seed, blocked families excluded",
            "sha256": hashes, **detail,
        }
        (args.output_dir / "build_manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
        print(f"Wrote {len(guesses):,} guess candidates and {len(targets):,} curated level words.", flush=True)
        print("Model preparation will report which requested words actually exist in Google News.", flush=True)
    except (ImportError, OSError, ValueError, RuntimeError) as exc:
        parser.exit(1, f"Vocabulary build failed: {exc}. Install backend/requirements-preparation.txt and run backend.scripts.prepare_nlp.\n")


if __name__ == "__main__":
    main()
